// Normalize stop name to handle subtle spelling differences in Bengali
export function normalizeStopName(name: string): string {
  if (!name) return '';
  return name
    .trim()
    .toLowerCase()
    .replace(/[,\/]/g, ' ')
    .replace(/\s+/g, ' ')
    .replace(/মোড়|মোড়/g, '')
    .replace(/বাজার মুখ/g, 'বাজার')
    .replace(/নিউমার্কেট/g, 'নিউ মার্কেট')
    .replace(/২ নং গেট/g, '২ নম্বর গেট')
    .replace(/কালু শাহ্/g, 'কালু শাহ')
    .replace(/কালু শাহ মাজার/g, 'কালু শাহ')
    .replace(/গরীবুল্লাহ শাহর মাজার/g, 'গরীবুল্লাহ শাহ মাজার')
    .replace(/উইমেন কলেজের মোড়/g, 'চট্টগ্রাম উইমেন কলেজ মোড়')
    .replace(/কাস্টমস মোড়/g, 'কাস্টমস')
    .replace(/ফ্রিপোর্ট/g, 'ফ্রি পোর্ট')
    .replace(/নয়াবাজার/g, 'নয়াবাজার')
    .replace(/সরাইপাড়া/g, 'সরাইপাড়া')
    .replace(/একে খানের মোড়|একে খান মোড়/g, 'একে খান মোড়')
    .replace(/অলংকার মার্কেট/g, 'অলংকার')
    .replace(/অলংকার মোড়/g, 'অলংকার')
    .replace(/কোতোয়ালি মোড়/g, 'কোতোয়ালি')
    .replace(/খুলশী ১, ২, ৩, ৪|খুলশী ১, ২, ৩/g, 'খুলশী')
    .trim();
}

